"""Monte Carlo estimation of pi on an AWS EMR Spark cluster.

Same algorithm as 03-spark, with larger workloads. Results are collected and
printed after the Spark session is closed so they are not buried in YARN logs.
"""

import random
from time import time

from pyspark.sql import SparkSession

spark = SparkSession.builder.appName("MonteCarloPi").getOrCreate()
sc = spark.sparkContext

# Number of tasks (RDD partitions) the workload is split into
NUM_TASKS = 200

# Total number of points per experiment: 50, 100 and 500 million
POINT_COUNTS = [n * 1_000_000 for n in (50, 100, 500)]


def count_points_in_circle(points: int) -> int:
    """Count random points that fall inside the unit circle.

    Args:
        points: Number of points generated by this task.

    Returns:
        Number of points with x^2 + y^2 <= 1.
    """
    rnd = random.random
    count = 0
    for _ in range(points):
        x = rnd()
        y = rnd()
        if x * x + y * y <= 1:
            count += 1
    return count


report = []

for total_points in POINT_COUNTS:
    # Every task processes the same number of points
    points_per_task = total_points // NUM_TASKS

    start = time()

    # One RDD element (and partition) per task
    rdd = sc.parallelize([points_per_task] * NUM_TASKS, NUM_TASKS)
    results = rdd.map(count_points_in_circle).collect()

    # pi = 4 * (points inside the circle / total points)
    pi = 4 * sum(results) / total_points

    elapsed = time() - start
    report.append(
        f"Points: {total_points}, Pi: {pi}, "
        f"Time: {elapsed:.3f} s, Throughput: {total_points / elapsed:.0f} points/s"
    )

spark.stop()

for line in report:
    print(line)
