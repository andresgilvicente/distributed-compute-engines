"""Monte Carlo estimation of pi on a Dask cluster."""

from time import time

import numpy as np
from dask.distributed import Client

# Connect to the Dask scheduler
client = Client("tcp://localhost:8786")

# Number of tasks the workload is split into
NUM_TASKS = 200

# Total number of points per experiment: 5, 10 and 50 million
POINT_COUNTS = [n * 1_000_000 for n in (5, 10, 50)]


def count_points_in_circle(points: int, seed: int) -> int:
    """Count random points that fall inside the unit circle.

    Args:
        points: Number of points generated by this task.
        seed: Seed of the random generator, so each task draws different points.

    Returns:
        Number of points with x^2 + y^2 <= 1.
    """
    np.random.seed(seed)
    x, y = np.random.random(points), np.random.random(points)
    return int(((x**2 + y**2) <= 1).sum())


for total_points in POINT_COUNTS:
    # Every task processes the same number of points
    points_per_task = total_points // NUM_TASKS

    start = time()

    # client.submit() returns a Future: a reference to a result not yet computed
    futures = [
        client.submit(
            count_points_in_circle, points_per_task, np.random.randint(total_points)
        )
        for _ in range(NUM_TASKS)
    ]

    # client.gather() blocks until all futures resolve
    # pi = 4 * (points inside the circle / total points)
    pi = 4 * sum(client.gather(futures)) / total_points

    elapsed = time() - start
    print(
        f"Points: {total_points}, Pi: {pi}, "
        f"Time: {elapsed:.3f} s, Throughput: {total_points / elapsed:.0f} points/s"
    )
